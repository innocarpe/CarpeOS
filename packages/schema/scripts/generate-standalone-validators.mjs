import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDir, "..");
const repoRoot = resolve(packageRoot, "../..");
const outputPath = resolve(packageRoot, "src/generated/standalone-validators.ts");
const check = process.argv.includes("--check");

const schemaEntries = [
  ["common", "spec/v1/schema/common.schema.json"],
  ["canonicalEvent", "spec/v1/schema/canonical-event.schema.json"],
  ["erasureLedger", "spec/v1/schema/erasure-ledger.schema.json"],
  ["mcpApi", "spec/v1/schema/mcp-api.schema.json"],
  ["obsidianProjection", "spec/v1/schema/obsidian-projection.schema.json"],
  ["retrievalProjection", "spec/v1/schema/retrieval-projection.schema.json"],
  ["syncApi", "spec/v1/schema/sync-api.schema.json"],
];

const schemas = schemaEntries.map(([name, path]) => {
  const schema = JSON.parse(readFileSync(resolve(repoRoot, path), "utf8"));
  if (typeof schema.$id !== "string") {
    throw new Error(`schema ${path} is missing $id`);
  }
  return { name, schema };
});

const ajv = new Ajv2020({
  allErrors: true,
  code: { source: true, esm: true },
});

for (const { schema } of schemas) {
  ajv.addSchema(schema);
}

const moduleMap = Object.fromEntries(schemas.map(({ name, schema }) => [name, schema.$id]));
const rawStandaloneCode = standaloneCode(ajv, moduleMap);
const { imports: standaloneImports, code: standaloneEsmCode } =
  repairStandaloneEsmRuntimeHelpers(rawStandaloneCode);
const generated = [
  "// @ts-nocheck",
  "/*",
  " * Generated by packages/schema/scripts/generate-standalone-validators.mjs.",
  " * Do not edit by hand; update spec/v1/schema/*.json and regenerate.",
  " */",
  ...standaloneImports,
  standaloneEsmCode,
  "",
  "export const standaloneValidators = {",
  ...schemas.map(({ name }) => `  ${name},`),
  "};",
  "",
].join("\n");

if (check) {
  const existing = readFileSync(outputPath, "utf8");
  if (existing !== generated) {
    throw new Error(
      `generated validators are stale: run pnpm --filter @carpeos/schema generate:validators (${relative(
        repoRoot,
        outputPath,
      )})`,
    );
  }
} else {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, generated);
}

function repairStandaloneEsmRuntimeHelpers(code) {
  const replacements = [
    {
      modulePath: "ajv/dist/runtime/equal",
      importPath: "ajv/dist/runtime/equal.js",
      moduleName: "ajvRuntimeEqualModule",
      localName: "ajvRuntimeEqual",
    },
    {
      modulePath: "ajv/dist/runtime/ucs2length",
      importPath: "ajv/dist/runtime/ucs2length.js",
      moduleName: "ajvRuntimeUcs2LengthModule",
      localName: "ajvRuntimeUcs2Length",
    },
  ];

  let repaired = code;
  const imports = [];
  for (const replacement of replacements) {
    const pattern = new RegExp(
      `const\\s+([A-Za-z_$][\\w$]*)\\s*=\\s*require\\("${escapeRegExp(
        replacement.modulePath,
      )}"\\)\\.default;`,
      "g",
    );
    const matches = [...repaired.matchAll(pattern)];
    if (matches.length !== 1) {
      throw new Error(
        `expected exactly one AJV standalone runtime helper for ${replacement.modulePath}, found ${matches.length}`,
      );
    }

    repaired = repaired.replace(pattern, `const $1 = ${replacement.localName};`);
    imports.push(`import ${replacement.moduleName} from "${replacement.importPath}";`);
  }

  imports.push(
    "",
    "// AJV 8.20 standalone ESM still emits CommonJS runtime helper references; normalize only these helpers.",
    "const ajvRuntimeEqual =",
    '  typeof ajvRuntimeEqualModule === "function" ? ajvRuntimeEqualModule : ajvRuntimeEqualModule.default;',
    "const ajvRuntimeUcs2Length =",
    '  typeof ajvRuntimeUcs2LengthModule === "function"',
    "    ? ajvRuntimeUcs2LengthModule",
    "    : ajvRuntimeUcs2LengthModule.default;",
    "",
  );

  assertNoGeneratedDynamicCode(repaired);
  return { imports, code: repaired };
}

function assertNoGeneratedDynamicCode(code) {
  const disallowed = [
    { label: "CommonJS require", pattern: /require\s*\(/ },
    { label: "runtime Function constructor", pattern: /\bFunction\s*\(/ },
    { label: "dynamic eval", pattern: /\beval\s*\(/ },
  ];

  for (const { label, pattern } of disallowed) {
    if (pattern.test(code)) {
      throw new Error(`generated standalone validators contain disallowed ${label}`);
    }
  }
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
